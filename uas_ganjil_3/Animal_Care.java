    private void TabelAnimalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TabelAnimalMouseClicked
        // TODO add your handling code here:
        int row = TabelAnimal.getSelectedRow();

        if (row >= 0) {
            InputIdProduk.setText(TabelAnimal.getValueAt(row, 0).toString());
            InputNamaProduk.setText(TabelAnimal.getValueAt(row, 1).toString());
            InputHarga.setText(TabelAnimal.getValueAt(row, 2).toString());
            InputStok.setText(TabelAnimal.getValueAt(row, 3).toString());
        }
    }//GEN-LAST:event_TabelAnimalMouseClicked

