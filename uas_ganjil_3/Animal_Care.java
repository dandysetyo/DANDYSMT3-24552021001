    private void PetFoodDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PetFoodDeleteActionPerformed
        // TODO add your handling code here:
        int id = Integer.parseInt(InputIdProduk.getText());
        if (dao.delete(id, ID_KATEGORI)) {
            JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
            loadTable();
            clear();
        }

    }//GEN-LAST:event_PetFoodDeleteActionPerformed

